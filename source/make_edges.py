"""Builds the version 3 links from the version 2 links and the audit table.

Reads   edges_v2.py                 the version 2 links (frozen)
        research/v3_reconcile.csv   one row per version 2 link and per candidate, with the decision
        research/v3_coverage_*.json the re-read of every cited source (for each record's source URL)
        v3_labels.py                labels of new links, and labels that change
Writes  edges.py                    EDGES, SHORT, SINCE_YEAR, CORE_KINDS, CONTEXT_KINDS (generated)
        v3_evidence.json            per link: verdict, whether the quote names the influence, the audit
                                    note, and any new quote or source (read by make_sources.py)
"""
import csv, glob, json, os, pprint
HERE = os.path.dirname(os.path.abspath(__file__))
V2 = {}
exec(open(os.path.join(HERE, "edges_v2.py"), encoding="utf-8").read(), V2)
LAB = {}
exec(open(os.path.join(HERE, "v3_labels.py"), encoding="utf-8").read(), LAB)
rows = list(csv.DictReader(open(os.path.join(HERE, "research", "v3_reconcile.csv"), encoding="utf-8")))
SID_URL = {}
for f in sorted(glob.glob(os.path.join(HERE, "research", "v3_coverage_*.json"))):
    for s in json.load(open(f, encoding="utf-8")):
        if s.get("url"): SID_URL[s["sid"]] = s["url"]
ROW = {(r["frm"], r["to"]): r for r in rows}
DESIGN = ("design", "syntax", "type")
ST = {"strong": "s", "weak": "d"}
STN = {"s": "strong", "d": "weak"}

edges, short, since_year, evid = [], {}, {}, {}
v2keys = [(e[0], e[1]) for e in V2["EDGES"]]
assert all(k in ROW for k in v2keys), "version 2 link missing from the audit table"

def year(r):
    return int(float(r["since_year"])) if r["since_year"] else None

for a, b, label, sty, kind, since in V2["EDGES"]:
    r = ROW[(a, b)]
    if r["recommend"] != "keep":
        continue                                   # dropped, or rerouted through a new language
    k = (a, b)
    sh = V2["SHORT"].get(k)
    if k in LAB["FIX"]:
        label, sh, tag = LAB["FIX"][k]
        if tag is not None: since = tag or None
    nsty, nkind, nver = ST[r["v3_strength"]], r["v3_kind"], r["v3_verdict"]
    assert nkind in DESIGN or nsty == "d", f"{k}: a link by another route must be weak"
    ch = []
    if nsty != sty: ch.append(f"strength {STN[sty]} to {STN[nsty]}")
    if nkind != kind: ch.append(f"kind {kind} to {nkind}")
    if nver != r["v2_verdict"]: ch.append(f"verdict {r['v2_verdict']} to {nver}")
    ev = dict(new=False, verdict=nver, names_it=r["source_names_it"] or "no")
    if r["citation"]:                              # a different source now carries the link
        ev.update(quote=r["quote"], citation=r["citation"], url=r["url"]); ch.append("quote and source updated")
    elif "better quote" in r["change"] and r["quote_conf"] == "high" and r["quote"]:
        ev.update(quote=r["quote"]); ch.append("quote replaced by one that states the influence")
    if k in LAB["FIX"]: ch.append("label revised")
    ev["audit"] = ("Version 3: " + "; ".join(ch) + ".") if ch else ""
    edges.append((a, b, label, nsty, nkind, since))
    if sh: short[k] = sh
    if since: since_year[k] = year(r)
    evid[k] = ev

for r in rows:
    if r["in_v2"] == "yes" or r["recommend"] != "add":
        continue
    k = (r["frm"], r["to"])
    label, sh, tag = LAB["NEW"][k]
    nsty, nkind = ST[r["v3_strength"]], r["v3_kind"]
    assert nkind in DESIGN or nsty == "d", f"{k}: a link by another route must be weak"
    ev = dict(new=True, verdict=r["v3_verdict"], names_it=r["source_names_it"] or "no", quote=r["quote"])
    if r["citation"]:
        ev.update(citation=r["citation"], url=r["url"])
        ev["audit"] = "New in version 3 (from a source not cited in version 2)."
    else:
        ev["src_url"] = SID_URL[r["sid"]]          # same source as a version 2 link: make_sources.py copies its citation
        ev["audit"] = "New in version 3 (named in a source that version 2 already cited)."
    edges.append((k[0], k[1], label, nsty, nkind, tag))
    short[k] = sh
    if tag: since_year[k] = year(r)
    evid[k] = ev

assert len({(e[0], e[1]) for e in edges}) == len(edges), "duplicate link"
assert all(since_year.get((e[0], e[1])) for e in edges if e[5]), [e[:2] for e in edges if e[5] and not since_year.get((e[0], e[1]))]
out = ["# Influence links (version 3), generated by make_edges.py from edges_v2.py and research/v3_reconcile.csv.",
       "# (from_id, to_id, label, strength, kind, since)",
       '#   strength: "s" strong (solid line), "d" weak (dotted line). A link by a route other than design is always weak.',
       '#   kind: "design", "syntax", "type"; other routes: "platform", "implementation", "library", "product", "organizational".',
       "#   since: None for the original design; a version tag when the influence arrived later (its year is in SINCE_YEAR).",
       "EDGES = " + pprint.pformat(edges, width=160), "",
       "SHORT = " + pprint.pformat(short, width=160), "",
       "SINCE_YEAR = " + pprint.pformat(since_year, width=160), "",
       "CORE_KINDS = {" + ", ".join(repr(x) for x in sorted(V2["CORE_KINDS"])) + "}",
       "CONTEXT_KINDS = {" + ", ".join(repr(x) for x in sorted(V2["CONTEXT_KINDS"])) + "}", ""]
open(os.path.join(HERE, "edges.py"), "w", encoding="utf-8", newline="\n").write("\n".join(out))
json.dump({f"{a}>{b}": v for (a, b), v in evid.items()}, open(os.path.join(HERE, "v3_evidence.json"), "w", encoding="utf-8", newline="\n"),
          indent=1, ensure_ascii=False)
if __name__ == "__main__":
    from collections import Counter
    print("links", len(edges), Counter(STN[e[3]] for e in edges), "new", sum(v["new"] for v in evid.values()),
          "later-version", sum(1 for e in edges if e[5]), "kinds", dict(Counter(e[4] for e in edges)))
